#!/usr/bin/env node
// Regenerates scripts/data/moc-error-codes.json: the first moc release that
// contains each M-code, used by check-project.js to verify that a skill's
// declared moc floor covers every diagnostic it documents.
//
// Requires a local dfinity/motoko checkout (the git history is what dates a
// code; the GitHub API cannot answer "which release first contained this").
//
// Resolves against the latest moc RELEASE tag, not master: a code present in
// every shipped release but deleted on master (as M0219/M0220 were by the
// persistent-by-default change) must still count as available to users.
//
//   node scripts/update-moc-error-codes.js --motoko ~/src/motoko [--ref <tag>]

import { execFileSync } from "child_process";
import { writeFileSync } from "fs";
import { join } from "path";
import { ROOT } from "./lib/parse-skill.js";

const args = process.argv.slice(2);
const argOf = (name, fallback) => {
  const i = args.indexOf(name);
  return i !== -1 && args[i + 1] ? args[i + 1] : fallback;
};

const repo = argOf("--motoko", process.env.MOTOKO_REPO);
if (!repo) {
  console.error("usage: node scripts/update-moc-error-codes.js --motoko <path-to-dfinity/motoko> [--ref origin/master]");
  console.error("       (or set MOTOKO_REPO)");
  process.exit(1);
}

const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" }).trim();
const CODES_FILE = "src/lang_utils/error_codes.ml";

const isRelease = (t) => /^\d+\.\d+\.\d+$/.test(t);
const cmpSemver = (a, b) => {
  const [x, y] = [a, b].map((v) => v.split(".").map(Number));
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
};

const releases = git("tag").split("\n").map((t) => t.trim()).filter(isRelease).sort(cmpSemver);
const ref = argOf("--ref", releases.at(-1));
const head = git("rev-parse", ref);
const codes = [...new Set(git("show", `${ref}:${CODES_FILE}`).match(/M0\d{3}/g) ?? [])].sort();
if (codes.length === 0) {
  console.error(`No M-codes found in ${ref}:${CODES_FILE} — wrong ref or the file moved.`);
  process.exit(1);
}

// A release tag "contains" the commit that introduced the code iff that code is
// reachable from the tag. Tags are plain semver (1.15.0); ignore sdk-*/test-*.
const map = {};
const unresolved = [];
for (const code of codes) {
  // Oldest commit touching this literal in error_codes.ml == the one that added it.
  const commits = git("log", ref, "--format=%H", "-S", `"${code}"`, "--", CODES_FILE).split("\n").filter(Boolean);
  const introduced = commits.at(-1);
  if (!introduced) { unresolved.push(code); continue; }
  const tags = git("tag", "--contains", introduced).split("\n").map((t) => t.trim()).filter(isRelease);
  if (tags.length === 0) { unresolved.push(code); continue; } // in master, not yet released
  map[code] = tags.sort(cmpSemver)[0];
}

const out = {
  _comment: "Generated by scripts/update-moc-error-codes.js — do not edit by hand. Maps each moc diagnostic to the first moc release containing it.",
  _motokoRelease: ref,
  _motokoCommit: head,
  _generated: new Date().toISOString().slice(0, 10),
  _unresolved: unresolved,
  codes: map,
};
const dest = join(ROOT, "scripts", "data", "moc-error-codes.json");
writeFileSync(dest, JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote ${dest}: ${Object.keys(map).length} codes from moc ${ref} (${head.slice(0, 9)})`);
if (unresolved.length) console.log(`Unresolved: ${unresolved.join(", ")}`);
